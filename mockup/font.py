ACC={'Á':'A','É':'E','Í':'I','Ó':'O','Ú':'U'}
def text(img,x,y,s,col,sh=None):
    s=s.upper()
    cx=x
    for ch in s:
        acc=None
        if ch in ACC: acc='acute'; ch=ACC[ch]
        if ch=='Ñ': acc='tilde'; ch='N'
        g=G.get(ch,G['?']); w=len(g[0])
        for gy,row in enumerate(g):
            for gx,c in enumerate(row):
                if c=='#':
                    if sh: img.putpixel((cx+gx+1,y+gy+1),sh)
                    img.putpixel((cx+gx,y+gy),col)
        if acc=='acute':
            for p in [(w//2+1,-2),(w//2,-1)]:
                img.putpixel((cx+p[0],y+p[1]),col)
        if acc=='tilde':
            for p in [(1,-2),(2,-2),(3,-1),(4,-2)]:
                img.putpixel((cx+p[0],y+p[1]),col)
        cx+=w+1
    return cx-x
def width(s):
    s=s.upper(); t=0
    for ch in s:
        ch={'Á':'A','É':'E','Í':'I','Ó':'O','Ú':'U','Ñ':'N'}.get(ch,ch)
        t+=len(G.get(ch,G['?'])[0])+1
    return t-1
